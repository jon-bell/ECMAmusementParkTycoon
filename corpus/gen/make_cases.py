#!/usr/bin/env python3
"""Write the generated corpus cases (corpus/public/*.txt, corpus/heldout/*.txt).

Every generated case is a plain oracle script (oracle/README.md); this generator only documents
how they were made and keeps them consistent. Re-running it rewrites the same files. Families:

  tour-scNN-*   one per shipped scenario 0-20: load, close the objective window, open the park,
                then view the whole map from all four rotations at zoom 1:4 (gen/tour.py). The
                view is the game's own rendering of every ride, scenery item and guest in the park,
                which is most of CODESEG (the ride painters); the simulation runs meanwhile.

  catalogue-*  ride catalogue (gen/catalogue.py): every track piece the construction window offers
                for every ride type, built in Forest Frontiers and viewed in all rotations.

  viewopts-*   View-menu options with local tours (gen/tour.py viewopts); public sc07, held-out sc15.
  uitour-*     the game's windows and tabs by clicks (gen/uitour.py); public sc03, held-out sc15.
  park-ff-*    a working park built with commands in Forest Frontiers, run ~1 month (gen/park.py).

Assignment to public/held-out: gen/split.py (recorded seed, about one third held out per family)
for families of independent members (tours); the catalogue is split by design (see
catalogue_cases): public covers every ride type in direction 0, held-out covers every ride type
again with random directions and other groupings, so neither side has code the other lacks.

  make_cases.py [--dry-run]
"""
import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CORPUS = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import split  # noqa: E402
import tour   # noqa: E402

SCENARIOS = ['forest-frontiers', 'dynamite-dunes', 'leafy-lake', 'diamond-heights', 'evergreen-gardens',
             'bumbly-beach', 'trinity-islands', 'katies-dreamland', 'pokey-park', 'white-water-park',
             'millennium-mines', 'karts-coasters', 'mels-world', 'mystic-mountain', 'pacific-pyramids',
             'crumbly-woods', 'paradise-pier', 'lightning-peaks', 'ivory-towers', 'rainbow-valley',
             'thunder-rock']
OBJECTIVE_CLOSE = (427, 156)   # close box of the objective window every scenario opens with


def header(lines, what):
    return [f'# {ln}' for ln in what.splitlines()] + ['# generated by corpus/gen/make_cases.py'] + lines


def tour_case(n):
    seed = 7100000 + 7919 * n
    L = [f'seed {seed}', f'frame 1 load {n}',
         f'frame +10 mouse {OBJECTIVE_CLOSE[0]} {OBJECTIVE_CLOSE[1]} 1',
         f'frame +12 mouse {OBJECTIVE_CLOSE[0]} {OBJECTIVE_CLOSE[1]} 3',
         'tick 1 cmd 33 ebx=1 edx=0x100        # SET_PARK_OPEN dh=1']
    T, t = tour.tour(20)
    L += T
    L.append(f'frame +{t + 10} quit')
    what = (f'Scenario {n} ({SCENARIOS[n]}): open the park, then tour the whole map at zoom 1:4 in all four\n'
            f'rotations (arrow keys scroll, toolbar buttons rotate/zoom). {t + 10} frames after the load.')
    return f'tour-sc{n:02d}-{SCENARIOS[n]}', header(L, what)


CATALOGUE_PUBLIC = [('coasters-1', [0, 1, 2]), ('coasters-2', [3, 4, 15]), ('coasters-3', [17, 19]),
                    ('coasters-4', [44, 13, 16]), ('tracked', [5, 6, 7, 8, 9, 10, 11, 18, 22, 23, 24, 42]),
                    ('flat', [12, 14, 20, 21] + list(range(25, 42)) + [43, 45, 46, 47, 48])]
CATALOGUE_HELDOUT = [('random-1', [0, 2, 4, 5, 6, 7, 8, 9, 10, 11, 12, 14] + list(range(25, 34))),
                     ('random-2', [1, 3, 13, 16, 18, 20, 21, 22, 23, 24] + list(range(34, 42))),
                     ('random-3', [15, 17, 19, 42, 44, 43, 45, 46, 47, 48])]


def catalogue_cases():
    """Ride catalogue (gen/catalogue.py). Public: every ride type, pieces in direction 0.
    Held-out: every ride type again, in other groups, other seeds, random piece directions (the
    same distribution of inputs, independent samples)."""
    import random
    import catalogue
    from rctexe import Exe
    if not os.path.exists(catalogue.DEFAULT_MAP):
        raise SystemExit(f'{catalogue.DEFAULT_MAP} missing: run the selector discovery first:\n'
                         '  python3 corpus/gen/catalogue.py probe-script out/corpus/selector-probe.txt\n'
                         '  scripts/oracle-run.sh out/corpus/selector-probe out/corpus/selector-probe.txt\n'
                         '  python3 corpus/gen/catalogue.py probe-parse out/corpus/selector-probe/trace.bin')
    exe, smap = Exe(), json.load(open(catalogue.DEFAULT_MAP))
    out = []
    for i, (nm, types) in enumerate(CATALOGUE_PUBLIC + CATALOGUE_HELDOUT):
        held = i >= len(CATALOGUE_PUBLIC)
        seed = 7300000 + 1009 * i
        L, total = catalogue.case(types, smap, exe, seed, random.Random(seed) if held else None)
        what = (f'Ride catalogue {nm}: in Forest Frontiers, for ride types {types}, build every track piece\n'
                f'the construction window offers ({total} placements, '
                f'{"random directions" if held else "direction 0"}), view them at\n'
                f'zoom 1:4, 1:2, 1:1 in four rotations, demolish; see corpus/gen/catalogue.py.')
        out.append((f'catalogue-{nm}', header(L, what), 'heldout' if held else 'public'))
    return out


def viewopts_case(n, held):
    seed = 7500000 + 811 * n
    L = [f'seed {seed}', f'frame 1 load {n}',
         f'frame +10 mouse {OBJECTIVE_CLOSE[0]} {OBJECTIVE_CLOSE[1]} 1',
         f'frame +12 mouse {OBJECTIVE_CLOSE[0]} {OBJECTIVE_CLOSE[1]} 3',
         'tick 1 cmd 33 ebx=1 edx=0x100        # SET_PARK_OPEN dh=1']
    T, t = tour.viewopts(20)
    L += T + [f'frame +{t + 10} quit']
    what = (f'Scenario {n} ({SCENARIOS[n]}): View-menu options (underground, see-through, invisible\n'
            f'supports/people, gridlines, height marks) toggled in three groups, each followed by a local\n'
            f'zoom-1:2 tour in four rotations (gen/tour.py viewopts).')
    return f'viewopts-sc{n:02d}-{SCENARIOS[n]}', header(L, what), 'heldout' if held else 'public'


def uitour_case(n, rows, held):
    import uitour
    L = [f'seed {7600000 + 977 * n}'] + uitour.uitour(n, ride_rows=rows)
    L.append('frame +60 quit')
    what = (f'Scenario {n} ({SCENARIOS[n]}): UI tour (gen/uitour.py): ride list and every ride window tab,\n'
            f'guest and staff lists and windows, finances, research, park window tabs, map, messages,\n'
            f'scenery, land, path and new-ride windows. Each session starts from a fresh load.')
    return f'uitour-sc{n:02d}-{SCENARIOS[n]}', header(L, what), 'heldout' if held else 'public'


def park_case(held, ticks=33000):
    import park
    L = park.build('heldout' if held else 'public', ticks)
    what = (f'Forest Frontiers: build a small working park with game commands (gen/park.py: paths, flat\n'
            f'rides, stalls, a car-ride circuit, entrances/exits, staff, prices, research, marketing,\n'
            f'landscaping), open it, run {ticks} ticks (about two months) with mid-run changes.'
            + (' Held-out variant: other ride placement and seed.' if held else ''))
    return ('park-ff-' + ('variant' if held else 'build')), header(L, what), 'heldout' if held else 'public'


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--dry-run', action='store_true')
    a = ap.parse_args()
    families = {'tour': [tour_case(n) for n in range(len(SCENARIOS))]}
    fixed = catalogue_cases() + [viewopts_case(7, False), viewopts_case(15, True),
                                 uitour_case(3, 9, False), uitour_case(15, 9, True),
                                 park_case(False), park_case(True)]
    for name, lines, where in fixed:
        print(f'{where:8s} {name}')
        if not a.dry_run:
            with open(os.path.join(CORPUS, where, name + '.txt'), 'w') as f:
                f.write('\n'.join(lines) + '\n')
    for fam, cases in families.items():
        where = split.assign(fam, [c[0] for c in cases])
        for name, lines in cases:
            path = os.path.join(CORPUS, where[name], name + '.txt')
            other = os.path.join(CORPUS, 'public' if where[name] == 'heldout' else 'heldout', name + '.txt')
            print(f'{where[name]:8s} {name}')
            if a.dry_run:
                continue
            if os.path.exists(other):
                os.remove(other)
            with open(path, 'w') as f:
                f.write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
